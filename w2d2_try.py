# 最后一段 · else 和 finally 的执行顺序
# ══════════════════════════════════════════════════════════
# 下面这个函数已经写好了，只有 finally 里是空的。
# 先把 finally 补一行 print("finally 执行了")
# 然后预测四次调用的打印顺序，写在下面注释里，再按 F5。

def divide(a, b):
    try:
        result = a / b
    except ZeroDivisionError:
        print("除数不能为 0")
        return None
    else:
        print("没出错，走到 else")
        return result
    finally:
        # 步骤：在这里补一行 print("finally 执行了")
        print("finally 执行了")

# 预测顺序（写四行）：
#   divide(10, 2) →5
#   divide(10, 0) →除数不能为 0
#   divide(0, 5)  →0
#   divide(10, 0) 里 try 已经 return None 了，finally 还执行吗？ →可以
print(divide(10, 2))
print(divide(10, 0))
