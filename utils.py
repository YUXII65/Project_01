# ── 步骤 1 ──────────────────────────────
# 定义函数，名字叫 is_prime，接收一个参数 n
# 形状：def 函数名(参数名):
# 这一行末尾是冒号。
# ★ 不要单独按 F5：def 下面还没东西，会报 IndentationError。
#   连步骤 2 一起写完再跑。
def is_prime(n):
    if n <2:
        return False
    for i in range(2,n):
        if n%i==0:
            return False
    return True
if __name__ == "__main__":
    print(is_prime(2))
    print(is_prime(9))
    print(is_prime(97))
    print(is_prime(1))


